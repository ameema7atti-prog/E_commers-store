      const [isLoggedIn, setIsLoggedIn] = useState(false);
      const [isAdmin, setIsAdmin] = useState(false);
      const [authMode, setAuthMode] = useState('login');
      const [email, setEmail] = useState('');
      const [password, setPassword] = useState('');

